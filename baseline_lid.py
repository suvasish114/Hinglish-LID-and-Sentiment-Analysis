def make_token_metrics(eval_pred):
    logits, labels = eval_pred

    if isinstance(logits, tuple):
        logits = logits[0]

    pred_ids = np.argmax(logits, axis=-1)

    mask = labels != -100

    y_true = labels[mask].tolist()
    y_pred = pred_ids[mask].tolist()

    p_micro, r_micro, f_micro, _ = precision_recall_fscore_support(
        y_true,
        y_pred,
        labels=[0, 1, 2],
        average="micro",
        zero_division=0
    )

    p_macro, r_macro, f_macro, _ = precision_recall_fscore_support(
        y_true,
        y_pred,
        labels=[0, 1, 2],
        average="macro",
        zero_division=0
    )

    return {
        "accuracy": accuracy_score(y_true, y_pred),
        "micro_precision": p_micro,
        "micro_recall": r_micro,
        "micro_f1": f_micro,
        "macro_precision": p_macro,
        "macro_recall": r_macro,
        "macro_f1": f_macro
    }


def print_encoder_prediction_metrics(
    trainer, test_dataset, test_frame, name
):
    output = trainer.predict(test_dataset)

    logits = (
        output.predictions[0]
        if isinstance(output.predictions, tuple)
        else output.predictions
    )

    pred_ids = np.argmax(logits, axis=-1)

    gold_rows = []
    pred_rows = []

    test_frame = test_frame.reset_index(drop=True)

    for i, row in test_frame.iterrows():

        encoded_labels = test_dataset[i]["labels"].cpu().numpy()

        positions = np.where(encoded_labels != -100)[0]

        gold = row["gold_tags"]

        if len(positions) != len(gold):
            raise ValueError(
                f"Alignment error at row {i}: "
                f"{len(positions)} positions vs {len(gold)} gold labels"
            )

        predicted = [
            ID2LABEL[int(pred_ids[i][pos])]
            for pos in positions
        ]

        if len(predicted) != len(row["tokens"]):
            raise ValueError(
                f"Prediction mismatch at row {i}"
            )

        gold_rows.append(gold)
        pred_rows.append(predicted)

    metrics = calculate_lid_metrics(
        gold_rows,
        pred_rows,
        verbose=True
    )

    prediction_file = f"{name}_test_predictions.csv"

    prediction_df = pd.DataFrame({
        "id": (
            test_frame["id"]
            if "id" in test_frame.columns
            else np.arange(len(test_frame))
        ),
        "tokens": test_frame["tokens"].apply(
            lambda x: json.dumps(x, ensure_ascii=False)
        ),
        "gold_tags": [
            json.dumps(x) for x in gold_rows
        ],
        "pred_tags": [
            json.dumps(x) for x in pred_rows
        ]
    })

    prediction_df.to_csv(prediction_file, index=False)

    print("Saved:", prediction_file)

    return metrics, prediction_df


