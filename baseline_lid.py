import torch.nn as nn
import torch.nn.functional as F
from transformers import AutoModelForCausalLM
from transformers.modeling_outputs import TokenClassifierOutput

INDICBERT_MODEL_ID = "ai4bharat/IndicBERT-v3-1B"

class IndicBertForLID(nn.Module):
    def __init__(self, model_id=INDICBERT_MODEL_ID, num_labels=3, freeze_backbone=True):
        super().__init__()

        self.backbone = AutoModelForCausalLM.from_pretrained(
            model_id,
            trust_remote_code=True,
            torch_dtype=torch.float16 if torch.cuda.is_available() else torch.float32,
        )

        hidden_size = getattr(
            self.backbone.config,
            "hidden_size",
            getattr(self.backbone.config, "d_model", None),
        )
        if hidden_size is None:
            raise ValueError("Could not find hidden_size/d_model in IndicBERT config.")

        self.dropout = nn.Dropout(0.1)
        self.classifier = nn.Linear(hidden_size, num_labels)
        self.config = self.backbone.config
        self.num_labels = num_labels

        if freeze_backbone:
            for param in self.backbone.parameters():
                param.requires_grad = False

        if hasattr(self.backbone.config, "use_cache"):
            self.backbone.config.use_cache = False

    def forward(self, input_ids=None, attention_mask=None, labels=None, **kwargs):
        outputs = self.backbone(
            input_ids=input_ids,
            attention_mask=attention_mask,
            output_hidden_states=True,
            return_dict=True,
            use_cache=False,
        )
        hidden_states = outputs.hidden_states[-1]
        logits = self.classifier(self.dropout(hidden_states))

        loss = None
        if labels is not None:
            loss = F.cross_entropy(
                logits.reshape(-1, self.num_labels),
                labels.reshape(-1),
                ignore_index=-100,
            )

        return TokenClassifierOutput(loss=loss, logits=logits)


