def make_tokenizer_safe(token, tokenizer):
    token = str(token)

    cleaned = "".join(
        ch for ch in token
        if unicodedata.category(ch) != "Cf"
    )

    if not cleaned or cleaned.isspace():
        cleaned = "EMPTYTOKEN"

    token_ids = tokenizer(cleaned, add_special_tokens=False)["input_ids"]
    if len(token_ids) == 0:
        cleaned = "EMPTYTOKEN"

    return cleaned


class SentiMixTokenDataset(Dataset):
    def __init__(self, frame, tokenizer, max_length=512):
        self.frame = frame.reset_index(drop=True)
        self.tokenizer = tokenizer
        self.max_length = max_length
        self.features = []

        if not getattr(tokenizer, "is_fast", False):
            raise ValueError(
                "A fast tokenizer is required because this dataset uses word_ids() "
                "to align subwords with original SentiMix tokens."
            )

        for row_idx, row in self.frame.iterrows():
            original_tokens = [str(t) for t in row["tokens"]]
            tags = [str(t).lower() for t in row["gold_tags"]]

            if len(original_tokens) != len(tags):
                raise ValueError(
                    f"Gold alignment error at row {row_idx}: "
                    f"{len(original_tokens)} tokens vs {len(tags)} tags."
                )

            tokenizer_tokens = [
                make_tokenizer_safe(token, tokenizer)
                for token in original_tokens
            ]

            encoded = tokenizer(
                tokenizer_tokens,
                is_split_into_words=True,
                truncation=False,
                padding=False,
                add_special_tokens=True,
            )

            if len(encoded["input_ids"]) > max_length:
                raise ValueError(
                    f"Sentence at row {row_idx} tokenizes to "
                    f"{len(encoded['input_ids'])} pieces, exceeding max_length={max_length}. "
                    "Use a larger model-supported max_length or implement word-boundary chunking."
                )

            word_ids = encoded.word_ids()
            covered_word_ids = {
                wid for wid in word_ids if wid is not None
            }
            expected_word_ids = set(range(len(original_tokens)))
            missing_word_ids = sorted(expected_word_ids - covered_word_ids)

            if missing_word_ids:
                details = [
                    {
                        "position": i,
                        "original": repr(original_tokens[i]),
                        "tokenizer_input": repr(tokenizer_tokens[i]),
                        "tag": tags[i],
                    }
                    for i in missing_word_ids
                ]
                raise ValueError(
                    f"Tokenizer alignment failed at row {row_idx}. "
                    f"Missing original token positions: {details}"
                )

            aligned_labels = []
            previous_word_id = None

            for word_id in word_ids:
                if word_id is None:
                    aligned_labels.append(-100)
                elif word_id != previous_word_id:
                    aligned_labels.append(LABEL2ID[tags[word_id]])
                else:
                    aligned_labels.append(-100)
                previous_word_id = word_id

            valid_label_count = sum(x != -100 for x in aligned_labels)
            if valid_label_count != len(original_tokens):
                raise ValueError(
                    f"Alignment failed at row {row_idx}: {valid_label_count} "
                    f"first-subword labels for {len(original_tokens)} tokens."
                )

            self.features.append({
                "input_ids": encoded["input_ids"],
                "attention_mask": encoded["attention_mask"],
                "labels": aligned_labels,
            })

    def __len__(self):
        return len(self.features)

    def __getitem__(self, idx):
        return {
            key: torch.tensor(value, dtype=torch.long)
            for key, value in self.features[idx].items()
        }

