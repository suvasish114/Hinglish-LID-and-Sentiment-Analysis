def make_lid_prompt(tokens, mode="zero-shot", demonstration=None, retry=False):
    n = len(tokens)
    prompt = f'''
You are doing token-level language identification (LID) for Hinglish text.

Label definitions:
{LID_LABEL_DESCRIPTION}

Important rules:
1. Classify EACH item in the input token list separately.
2. Preserve the original order. Do not merge, split, remove, or add tokens.
3. Return exactly {n} labels because the input contains exactly {n} tokens.
4. Every label must be exactly one of: "h", "e", "o".
5. Output ONLY a valid JSON array, for example ["o", "h", "e"].
6. Do not output explanations, markdown, or any text outside the JSON array.

'''
    if mode == "one-shot" and demonstration is not None:
        prompt += (
            "Here is one correctly labeled example. Learn the labeling pattern "
            "from it, then label the new input.\n"
            + "Example tokens: "
            + json.dumps(demonstration["tokens"], ensure_ascii=False)
            + "\nExample labels: "
            + json.dumps(demonstration["tags"], ensure_ascii=False)
            + "\n\n"
        )

    if retry:
        prompt += (
            "Your previous answer did not have the required number of valid labels. "
            f"Return exactly {n} labels now. Count them before answering.\n"
        )

    prompt += (
        "Input tokens:\n"
        + json.dumps(tokens, ensure_ascii=False)
        + "\n\nOutput JSON label array only:"
    )
    return prompt


LABEL_ALIASES = {
    "h": "h", "hi": "h", "hindi": "h",
    "e": "e", "en": "e", "english": "e",
    "o": "o", "other": "o", "punctuation": "o", "symbol": "o",
}

def normalize_label(value):
    if value is None:
        return None
    value = str(value).strip().lower()
    value = re.sub(r"^[^a-z]+|[^a-z]+$", "", value)
    return LABEL_ALIASES.get(value)

def extract_label_array(response):
    arrays = re.findall(r"\[[\s\S]*?\]", str(response))
    for candidate in reversed(arrays):
        parsed = None
        try:
            parsed = json.loads(candidate)
        except Exception:
            try:
                parsed = ast.literal_eval(candidate)
            except Exception:
                pass

        if isinstance(parsed, list):
            return [normalize_label(x) for x in parsed]

    words = re.findall(r"(?<![A-Za-z])(Hindi|English|Other|h|e|o)(?![A-Za-z])",
                       str(response), flags=re.IGNORECASE)
    if words:
        return [normalize_label(x) for x in words]
    return None

def extract_single_label(response):
    if response is None:
        return None

    exact = normalize_label(str(response).strip().strip('"`* .,:;'))
    if exact is not None:
        return exact

    words = re.findall(r"(?<![A-Za-z])(Hindi|English|Other|h|e|o)(?![A-Za-z])",
                       str(response), flags=re.IGNORECASE)
    for word in words:
        label = normalize_label(word)
        if label is not None:
            return label
    return None


def classify_missing_token(tokens, token_index, generate_text_fn):
    target = tokens[token_index]
    prompt = f'''
Perform token-level language identification for Hinglish.
Labels: h = Hindi/Romanized Hindi, e = English, o = Other (punctuation, emoji,
username, URL, symbol, etc.).

Full sentence tokens (JSON):
{json.dumps(tokens, ensure_ascii=False)}

Target token position (0-based): {token_index}
Target token: {json.dumps(target, ensure_ascii=False)}

Classify ONLY the target token using the surrounding context.
Return exactly one character: h, e, or o. No explanation.
'''
    raw = generate_text_fn(prompt, max_new_tokens=8)
    label = extract_single_label(raw)

    if label is None:
        raw = generate_text_fn(
            prompt + "\nReminder: output only one of h, e, or o.",
            max_new_tokens=8,
        )
        label = extract_single_label(raw)

    return label if label is not None else "o"


def predict_lid_with_llm(tokens, generate_text_fn, mode="zero-shot"):
    demonstration = one_shot_example if mode == "one-shot" else None
    prompt = make_lid_prompt(tokens, mode, demonstration, retry=False)

    raw = generate_text_fn(prompt, max_new_tokens=max(32, 4 * len(tokens) + 24))
    pred = extract_label_array(raw)

    if pred is None or len(pred) != len(tokens) or any(x is None for x in pred):
        retry_prompt = make_lid_prompt(tokens, mode, demonstration, retry=True)
        raw = generate_text_fn(
            retry_prompt,
            max_new_tokens=max(32, 4 * len(tokens) + 24),
        )
        pred = extract_label_array(raw)

    if pred is None:
        pred = []

    pred = pred[:len(tokens)]
    if len(pred) < len(tokens):
        pred.extend([None] * (len(tokens) - len(pred)))

    for i, label in enumerate(pred):
        if label not in LABELS:
            pred[i] = classify_missing_token(tokens, i, generate_text_fn)

    assert len(pred) == len(tokens)
    assert all(label in LABELS for label in pred)
    return pred

def run_llm_evaluation(
    model_name,
    generate_text_fn,
    frame,
    mode,
    max_samples=None,
    output_prefix="llm",
):
    eval_frame = frame if max_samples is None else frame.head(max_samples)
    gold_rows = eval_frame["gold_tags"].tolist()
    pred_rows = []

    for _, row in tqdm(
        eval_frame.iterrows(),
        total=len(eval_frame),
        desc=f"{model_name} | {mode}",
    ):
        pred = predict_lid_with_llm(
            row["tokens"],
            generate_text_fn,
            mode=mode,
        )
        pred_rows.append(pred)

    metrics = calculate_lid_metrics(gold_rows, pred_rows, verbose=True)

    prediction_df = pd.DataFrame({
        "id": eval_frame["id"] if "id" in eval_frame.columns else np.arange(len(eval_frame)),
        "tokens": eval_frame["tokens"].apply(lambda x: json.dumps(x, ensure_ascii=False)),
        "gold_tags": [json.dumps(x) for x in gold_rows],
        "pred_tags": [json.dumps(x) for x in pred_rows],
    })
    prediction_file = f"{output_prefix}_{mode}_predictions.csv"
    prediction_df.to_csv(prediction_file, index=False)

    metrics_row = {
        "model": model_name,
        "setting": mode,
        "sentences": len(eval_frame),
        "tokens": sum(map(len, gold_rows)),
        **metrics,
    }
    print("Saved:", prediction_file)
    return metrics_row, prediction_df

