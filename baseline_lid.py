def parse_list_cell(value, column_name, row_number):
    if isinstance(value, list):
        parsed = value
    else:
        try:
            parsed = ast.literal_eval(str(value))
        except Exception as exc:
            raise ValueError(
                f"Could not parse {column_name} at row {row_number}: {value!r}"
            ) from exc

    if not isinstance(parsed, list):
        raise ValueError(
            f"{column_name} at row {row_number} is not a list: {type(parsed)}"
        )
    return parsed

def load_lid_csv(path):
    df = pd.read_csv(path)
    required = {"sentence", "tags"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"{path} is missing required columns: {missing}")

    token_rows, tag_rows = [], []
    for row_number, row in df.iterrows():
        tokens = parse_list_cell(row["sentence"], "sentence", row_number)
        tags = parse_list_cell(row["tags"], "tags", row_number)

        if len(tokens) != len(tags):
            raise ValueError(
                f"Gold alignment error in {path}, row {row_number}: "
                f"{len(tokens)} tokens but {len(tags)} tags."
            )

        unknown = set(tags) - set(LABELS)
        if unknown:
            raise ValueError(
                f"Unknown LID labels in {path}, row {row_number}: {unknown}"
            )

        token_rows.append([str(x) for x in tokens])
        tag_rows.append([str(x).lower() for x in tags])

    df = df.copy()
    df["tokens"] = token_rows
    df["gold_tags"] = tag_rows
    return df

