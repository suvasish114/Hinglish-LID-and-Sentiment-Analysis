def calculate_lid_metrics(gold_rows, pred_rows, verbose=True):
    if len(gold_rows) != len(pred_rows):
        raise ValueError(
            f"Sentence count mismatch: {len(gold_rows)} gold vs {len(pred_rows)} predictions"
        )

    y_true, y_pred = [], []
    for row_index, (gold, pred) in enumerate(zip(gold_rows, pred_rows)):
        if len(gold) != len(pred):
            raise ValueError(
                f"Prediction length mismatch at row {row_index}: "
                f"{len(gold)} gold labels vs {len(pred)} predictions"
            )
        y_true.extend(gold)
        y_pred.extend(pred)

    metrics = {"accuracy": accuracy_score(y_true, y_pred)}
    for average in ["micro", "macro", "weighted"]:
        p, r, f1, _ = precision_recall_fscore_support(
            y_true,
            y_pred,
            labels=LABELS,
            average=average,
            zero_division=0,
        )
        metrics[f"{average}_precision"] = p
        metrics[f"{average}_recall"] = r
        metrics[f"{average}_f1"] = f1

    if verbose:
        print(f"Total evaluated tokens: {len(y_true):,}")
        print(f"Accuracy: {metrics['accuracy']:.4f}")
        print("\nAggregate metrics:")
        print(pd.DataFrame([
            {
                "average": avg,
                "precision": metrics[f"{avg}_precision"],
                "recall": metrics[f"{avg}_recall"],
                "f1": metrics[f"{avg}_f1"],
            }
            for avg in ["micro", "macro", "weighted"]
        ]).round(4).to_string(index=False))
        print("\nPer-class report:")
        print(classification_report(
            y_true, y_pred, labels=LABELS, zero_division=0, digits=4
        ))

    return metrics

def choose_one_shot_example(frame):
    candidates = []
    for idx, row in frame.iterrows():
        tags = row["gold_tags"]
        if set(tags) == set(LABELS):
            candidates.append((len(row["tokens"]), idx))

    if not candidates:
        raise ValueError(
            "No single training sentence contains h, e, and o. "
            "Use a small few-shot set with one sentence per missing label."
        )

    _, best_idx = min(candidates)
    return frame.loc[best_idx]

