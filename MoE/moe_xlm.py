        f"Epoch {epoch + 1}/{EPOCHS} | "
        f"loss={train_loss:.4f} | "
        f"LID loss={train_lid_loss:.4f} | "
        f"sentiment loss={train_sentiment_loss:.4f} | "
        f"dev sentiment macro-F1={val_sent_f1:.4f} | "
        f"dev LID macro-F1={val_lid_f1:.4f} | "
