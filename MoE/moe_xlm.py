def predict_sentence(text):
    model.eval()
    words = str(text).strip().split()
    if not words:
        raise ValueError("Input sentence is empty.")

    encoding = tokenizer(
        words,
        is_split_into_words=True,
        truncation=True,
        max_length=MAX_LENGTH,
        return_tensors="pt"
    )
    word_ids = encoding.word_ids(batch_index=0)

    input_ids = encoding["input_ids"].to(device)
    attention_mask = encoding["attention_mask"].to(device)
    word_mask = torch.tensor(
        [[1 if wid is not None else 0 for wid in word_ids]],
        dtype=torch.long,
        device=device
    )

    with torch.no_grad():
        outputs = model(input_ids, attention_mask, word_mask)

    sentiment_id = outputs["sentiment_logits"].argmax(dim=-1).item()
    token_pred_ids = outputs["lid_logits"].argmax(dim=-1)[0].cpu().tolist()

    # First subword prediction is the prediction for that original word.
    word_predictions = {}
    for position, word_id in enumerate(word_ids):
        if word_id is not None and word_id not in word_predictions:
            word_predictions[word_id] = id2lid[token_pred_ids[position]]

    word_results = [
        {"word": word, "lid": word_predictions.get(i, "TRUNCATED")}
        for i, word in enumerate(words)
    ]

    return {
        "text": text,
        "sentiment": id2sentiment[sentiment_id],
        "word_level_lid": word_results
    }

