def encode_dataframe(df, split_name):
    samples = []

    for row_index, row in df.iterrows():
        words = parse_row_tokens(row, row_index)
        tags = parse_row_tags(row, row_index)
        sentiment = str(row[SENTIMENT_COL]).strip()

        if len(words) != len(tags):
            raise ValueError(
                f"{split_name}, row {row_index}: {len(words)} tokens "
                f"but {len(tags)} tags."
            )
        if sentiment not in sentiment2id:
            raise ValueError(
                f"Unknown sentiment '{sentiment}' in {split_name}, row {row_index}."
            )

        encoding = tokenizer(
            words,
            is_split_into_words=True,
            truncation=True,
            max_length=MAX_LENGTH,
            padding="max_length",
            return_attention_mask=True
        )

        word_ids = encoding.word_ids()
        lid_targets = [-100] * MAX_LENGTH
        word_mask = [0] * MAX_LENGTH

        previous_word_id = None
        for position, word_id in enumerate(word_ids):
            if word_id is None:
                previous_word_id = None
                continue

            word_mask[position] = 1

            if word_id != previous_word_id:
                lid_targets[position] = lid2id[tags[word_id]]

            previous_word_id = word_id

        samples.append({
            "id": str(row[ID_COL]),
            "words": words,
            "input_ids": encoding["input_ids"],
            "attention_mask": encoding["attention_mask"],
            "word_mask": word_mask,
            "lid_labels": lid_targets,
            "sentiment_label": sentiment2id[sentiment]
        })

    return samples

