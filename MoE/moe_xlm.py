def parse_list_cell(value, column_name, row_index):
    if isinstance(value, list):
        parsed = value
    elif isinstance(value, str):
        try:
            parsed = ast.literal_eval(value)
        except (ValueError, SyntaxError) as exc:
            raise ValueError(
                f"Could not parse {column_name} at row {row_index}: {value[:150]}"
            ) from exc
    else:
        raise TypeError(
            f"Unexpected value type in {column_name}, row {row_index}: {type(value)}"
        )

    if not isinstance(parsed, (list, tuple)):
        raise ValueError(
            f"{column_name} at row {row_index} is not a list."
        )
    return [str(item).strip() for item in parsed]

def parse_row_tokens(row, row_index):
    return parse_list_cell(row[TEXT_COL], TEXT_COL, row_index)

def parse_row_tags(row, row_index):
    return [tag.lower() for tag in parse_list_cell(row[LID_COL], LID_COL, row_index)]

def validate_split(df, split_name):
    for row_index, row in df.iterrows():
        tokens = parse_row_tokens(row, row_index)
        tags = parse_row_tags(row, row_index)
