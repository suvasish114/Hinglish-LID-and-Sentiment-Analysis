class MoEExpert(nn.Module):
    def __init__(self, hidden_size, dropout):
        super().__init__()
        self.network = nn.Sequential(
            nn.Linear(hidden_size, hidden_size),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_size, hidden_size),
            nn.Dropout(dropout)
        )

    def forward(self, x):
        return self.network(x)


class MultiTaskMoE(nn.Module):
    def __init__(
        self,
        model_name,
        num_lid_classes,
        num_sentiment_classes,
        num_experts=4,
        dropout=0.2
    ):
        super().__init__()

        self.encoder = AutoModel.from_pretrained(model_name)
        hidden_size = self.encoder.config.hidden_size

        # Shared experts; each expert processes each contextual token vector.
        self.experts = nn.ModuleList([
            MoEExpert(hidden_size, dropout)
            for _ in range(num_experts)
        ])


        self.lid_gate = nn.Linear(hidden_size, num_experts)
        self.sentiment_gate = nn.Linear(hidden_size, num_experts)

        self.lid_classifier = nn.Sequential(
            nn.Dropout(dropout),
            nn.Linear(hidden_size, num_lid_classes)
        )

        # Attention pooling and sentence-level sentiment classifier.
        self.sentiment_attention = nn.Linear(hidden_size, 1)
        self.sentiment_classifier = nn.Sequential(
            nn.Dropout(dropout),
            nn.Linear(hidden_size, num_sentiment_classes)
        )

    def forward(self, input_ids, attention_mask, word_mask):
        encoder_output = self.encoder(
            input_ids=input_ids,
            attention_mask=attention_mask
        )
        hidden = encoder_output.last_hidden_state      # [batch, sequence_length, hidden_size]

        expert_outputs = torch.stack(
            [expert(hidden) for expert in self.experts],
            dim=1
        )                                               # [batch, num_experts, sequence_length, hidden_size]

        lid_weights = torch.softmax(self.lid_gate(hidden), dim=-1)
        sentiment_weights = torch.softmax(self.sentiment_gate(hidden), dim=-1)

        # Weighted sum over experts, independently for each task.
        lid_features = torch.einsum(
            "blk,bklh->blh", lid_weights, expert_outputs
        )
        sentiment_features = torch.einsum(
            "blk,bklh->blh", sentiment_weights, expert_outputs
        )

        lid_logits = self.lid_classifier(lid_features)

        # Pool only actual word/subword positions; exclude CLS, SEP and padding.
        attention_scores = self.sentiment_attention(
            sentiment_features
        ).squeeze(-1)
        attention_scores = attention_scores.masked_fill(
            word_mask == 0, -1e4
        )
        attention_weights = torch.softmax(attention_scores, dim=1)

        sentence_vector = torch.sum(
            sentiment_features * attention_weights.unsqueeze(-1),
            dim=1
        )
        sentiment_logits = self.sentiment_classifier(sentence_vector)

        return {
            "lid_logits": lid_logits,
            "sentiment_logits": sentiment_logits,
            "lid_gate_weights": lid_weights,
            "sentiment_gate_weights": sentiment_weights
        }


