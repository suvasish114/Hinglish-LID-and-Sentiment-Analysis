lid_criterion = nn.CrossEntropyLoss(ignore_index=-100)
sentiment_criterion = nn.CrossEntropyLoss()

def calculate_loss(outputs, batch):
    lid_logits = outputs["lid_logits"]
    sentiment_logits = outputs["sentiment_logits"]
    lid_targets = batch["lid_labels"]
    sentiment_targets = batch["sentiment_label"]

    lid_loss = lid_criterion(
        lid_logits.reshape(-1, lid_logits.size(-1)),
        lid_targets.reshape(-1)
    )
    sentiment_loss = sentiment_criterion(
        sentiment_logits,
        sentiment_targets
    )

    total_loss = (
        LID_LOSS_WEIGHT * lid_loss
        + (1.0 - LID_LOSS_WEIGHT) * sentiment_loss
    )
    return total_loss, lid_loss, sentiment_loss


