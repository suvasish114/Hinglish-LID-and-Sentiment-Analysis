def metric_dict(y_true, y_pred, labels):
    precision, recall, macro_f1, _ = precision_recall_fscore_support(
        y_true, y_pred, labels=list(range(len(labels))),
        average="macro", zero_division=0
    )
    w_precision, w_recall, weighted_f1, _ = precision_recall_fscore_support(
        y_true, y_pred, labels=list(range(len(labels))),
        average="weighted", zero_division=0
    )
    return {
        "accuracy": accuracy_score(y_true, y_pred),
        "macro_precision": precision,
        "macro_recall": recall,
        "macro_f1": macro_f1,
        "weighted_precision": w_precision,
        "weighted_recall": w_recall,
        "weighted_f1": weighted_f1
    }


def evaluate_model(model, loader, split_name="Evaluation", print_report=True):
    model.eval()
    sent_true, sent_pred = [], []
    lid_true, lid_pred = [], []

    with torch.no_grad():
        for batch in loader:
            input_ids = batch["input_ids"].to(device)
            attention_mask = batch["attention_mask"].to(device)
            word_mask = batch["word_mask"].to(device)

            outputs = model(input_ids, attention_mask, word_mask)

            sent_predictions = outputs["sentiment_logits"].argmax(dim=-1)
            sent_true.extend(batch["sentiment_label"].tolist())
            sent_pred.extend(sent_predictions.cpu().tolist())

            lid_predictions = outputs["lid_logits"].argmax(dim=-1).cpu()
            gold_lid = batch["lid_labels"]
            valid = gold_lid != -100
            lid_true.extend(gold_lid[valid].tolist())
            lid_pred.extend(lid_predictions[valid].tolist())

    sent_metrics = metric_dict(sent_true, sent_pred, sentiment_labels)
    lid_metrics = metric_dict(lid_true, lid_pred, lid_labels)

    if print_report:
        print(f"\n{split_name} — SENTIMENT")
        print(pd.Series(sent_metrics).round(4))
        print(classification_report(
            sent_true, sent_pred,
            labels=list(range(len(sentiment_labels))),
            target_names=sentiment_labels,
            zero_division=0
        ))

        print(f"\n{split_name} — WORD-LEVEL LID")
        print(pd.Series(lid_metrics).round(4))
        print(classification_report(
            lid_true, lid_pred,
            labels=list(range(len(lid_labels))),
            target_names=lid_labels,
            zero_division=0
        ))

    return {
        "sentiment": sent_metrics,
        "lid": lid_metrics,
        "sentiment_true": sent_true,
        "sentiment_pred": sent_pred,
        "lid_true": lid_true,
        "lid_pred": lid_pred
    }

